# ── ANSI colours (no external deps) ──────────────────────────────────────────

RESET = "\033[0m"
BOLD = "\033[1m"
DIM = "\033[2m"
GREEN = "\033[32m"
YELLOW = "\033[33m"
RED = "\033[31m"
CYAN = "\033[36m"
ORANGE = "\033[38;5;208m"


def _c(text: str, *codes: str) -> str:
    return "".join(codes) + text + RESET


# ── Status rendering ──────────────────────────────────────────────────────────


def _dot(connected: bool, pending: bool = False) -> str:
    if connected:
        return _c("●", GREEN)
    if pending:
        return _c("●", YELLOW)
    return _c("●", RED)


def _render_status(state: dict) -> str:
    discord = state.get("discord") or {}
    in_match = state.get("in_match", False)
    live = state.get("live_match_view") or {}

    tracker_on = state.get("connected") and state.get("listening")
    discord_on = discord.get("connected", False)
    requested = state.get("requested", False)

    tracker_label = (
        _c("Online", GREEN)
        if tracker_on
        else (_c("Connecting…", YELLOW) if requested else _c("Offline", RED))
    )
    discord_label = (
        _c("Online", GREEN)
        if discord_on
        else (
            _c("Reconnecting…", YELLOW)
            if discord.get("reconnecting")
            else _c("Offline", RED)
        )
    )

    lines = [
        "",
        f"  {_dot(bool(tracker_on), bool(requested))} Tracker  {tracker_label}    "
        f"{_dot(bool(discord_on), bool(discord.get('reconnecting')))} Discord  {discord_label}",
    ]

    if in_match and live:
        arena = live.get("arena") or "—"
        mode = live.get("mode") or "—"
        timer = live.get("time") or "—"
        status = live.get("status") or "—"
        t_score = live.get("team_score")
        o_score = live.get("opponent_score")
        score_txt = (
            f"{_c(str(t_score), ORANGE)}  —  {_c(str(o_score), CYAN)}"
            if t_score is not None and o_score is not None
            else "—"
        )

        lines += [
            "",
            f"  {_c('LIVE MATCH', BOLD)}",
            f"  {_c('Arena', DIM)}  {arena}   {_c('Mode', DIM)}  {mode}   "
            f"{_c('Timer', DIM)}  {timer}   {_c('Status', DIM)}  {status}",
            f"  {_c('Score', DIM)}  {score_txt}",
        ]
    else:
        lines.append(f"  {_c('No active match', DIM)}")

    lines.append("")
    return "\n".join(lines)


# ── Live loop ─────────────────────────────────────────────────────────────────


def _run_live(coordinator: AppCoordinator, stop: threading.Event) -> None:
    first = True
    prev_lines = 0

    while not stop.is_set():
        state = coordinator.get_live_state()
        output = _render_status(state)
        lines = output.count("\n") + 1

        if not first:
            # move cursor up to overwrite previous output
            sys.stdout.write(f"\033[{prev_lines}A\033[J")

        sys.stdout.write(output)
        sys.stdout.flush()
        prev_lines = lines
        first = False
        stop.wait(1.0)


# ── Preset subcommands ────────────────────────────────────────────────────────


def cmd_preset_list(coordinator: AppCoordinator) -> None:
    names = coordinator.list_presence_presets()
    if not names:
        print("No presets saved.")
        return
    for name in names:
        print(f"  • {name}")


def cmd_preset_load(coordinator: AppCoordinator, name: str) -> None:
    try:
        coordinator.load_presence_preset(name)
        print(_c(f"Preset '{name}' loaded.", GREEN))
    except ValueError as exc:
        print(_c(f"Error: {exc}", RED))


def cmd_preset_save(coordinator: AppCoordinator, name: str) -> None:
    try:
        coordinator.save_presence_preset(name)
        print(_c(f"Preset '{name}' saved.", GREEN))
    except ValueError as exc:
        print(_c(f"Error: {exc}", RED))


def cmd_preset_delete(coordinator: AppCoordinator, name: str) -> None:
    try:
        coordinator.delete_presence_preset(name)
        print(_c(f"Preset '{name}' deleted.", GREEN))
    except ValueError as exc:
        print(_c(f"Error: {exc}", RED))


