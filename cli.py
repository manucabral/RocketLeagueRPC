def main() -> None:
    args = build_parser().parse_args()

    log_level = args.log_level or ("DEBUG" if config.development_mode else "INFO")
    setup_logger(log_file=config.log_path)
    set_log_level(log_level)

    coordinator = AppCoordinator()

    # ── Preset-only commands (no connection needed) ──
    if args.command == "preset":
        if args.preset_cmd == "list":
            cmd_preset_list(coordinator)
        elif args.preset_cmd == "load":
            cmd_preset_load(coordinator, args.name)
        elif args.preset_cmd == "save":
            cmd_preset_save(coordinator, args.name)
        elif args.preset_cmd == "delete":
            cmd_preset_delete(coordinator, args.name)
        else:
            print("Usage: cli.py preset {list|load|save|delete}")
        return

    # ── Live mode ────────────────────────────────────
    print(_c(f"\n  Rocket League RPC  v{config.app_version}", BOLD))
    print(_c("  Press Ctrl+C to stop\n", DIM))

    if not args.no_tracker:
        coordinator.connect_tracker()

    if not args.no_discord:
        threading.Thread(
            target=coordinator.connect_discord_rpc,
            kwargs={"max_tries": MAX_CONNECT_TRIES},
            daemon=True,
            name="discord-startup-connect",
        ).start()

    stop = threading.Event()

    if not args.quiet:
        live_thread = threading.Thread(
            target=_run_live, args=(coordinator, stop), daemon=True
        )
        live_thread.start()

    try:
        while not stop.is_set():
            time.sleep(0.1)
    except KeyboardInterrupt:
        stop.set()

    if not args.quiet:
        live_thread.join(timeout=1.0)

    print(_c("\n  Shutting down…", DIM))
    coordinator.shutdown()
    print(_c("  Done.\n", DIM))


if __name__ == "__main__":
    main()
