def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="rl-rpc",
        description="Rocket League Discord Rich Presence — CLI",
    )
    p.add_argument("--no-tracker", action="store_true", help="Skip tracker connection")
    p.add_argument(
        "--no-discord", action="store_true", help="Skip Discord RPC connection"
    )
    p.add_argument("--quiet", action="store_true", help="No live status output")
    p.add_argument(
        "--log-level",
        default=None,
        metavar="LEVEL",
        help="Log level: DEBUG, INFO, WARNING (default: INFO)",
    )

    sub = p.add_subparsers(dest="command")

    preset = sub.add_parser("preset", help="Manage presence presets")
    preset_sub = preset.add_subparsers(dest="preset_cmd")
    preset_sub.add_parser("list", help="List saved presets")

    pl = preset_sub.add_parser("load", help="Load a preset")
    pl.add_argument("name")

    ps = preset_sub.add_parser("save", help="Save current config as preset")
    ps.add_argument("name")

    pd = preset_sub.add_parser("delete", help="Delete a preset")
    pd.add_argument("name")

